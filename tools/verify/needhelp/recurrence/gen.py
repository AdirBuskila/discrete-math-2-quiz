# Writes courses/recurrence/C0N.js from spec.build(). Run: py -I? no -- py tools/verify/needhelp/recurrence/gen.py
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import spec

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "..", "courses", "recurrence")

def js(v): return json.dumps(v, ensure_ascii=False)

def main():
    os.makedirs(OUT, exist_ok=True)
    for lv in spec.build():
        html = lv["lesson"]["html"]
        assert "`" not in html and "${" not in html, lv["id"]
        qs = ",\n".join("    " + js(q) for q in lv["questions"])
        body = ('/* recurrence course, level %s - generated by tools/verify/needhelp/recurrence/gen.py (every number machine-checked in spec.py) */\n'
                'COURSE_LEVEL("recurrence", {\n'
                '  id: %s, order: %d, icon: %s, title: %s,\n  goal: %s,\n  boss: %s,\n  source: %s,\n'
                '  lesson: { html: String.raw`%s` },\n  questions: [\n%s,\n  ],\n});\n') % (
            lv["id"], js(lv["id"]), lv["order"], js(lv["icon"]), js(lv["title"]), js(lv["goal"]),
            "true" if lv["boss"] else "false", js(lv["source"]), html, qs)
        with open(os.path.join(OUT, lv["id"] + ".js"), "w", encoding="utf8", newline="\n") as f:
            f.write(body)
        print("wrote", lv["id"], len(lv["questions"]))

if __name__ == "__main__":
    main()
