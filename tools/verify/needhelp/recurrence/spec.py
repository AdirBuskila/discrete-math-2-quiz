# Course "recurrence": every number is recomputed here by iterating the recurrence (brute force) and the level
# data is built from those values. gen.py writes courses/recurrence/C0N.js from build(); check.py re-loads the
# stored JS and asserts it equals build().
from fractions import Fraction as F
import json

# ---------- brute-force helpers ----------
def iterate(p, q, g, a0, a1, N):
    a = [F(a0), F(a1)]
    for n in range(2, N + 1):
        a.append(p * a[n - 1] + q * a[n - 2] + g(n))
    return a

def ev(terms, n):
    """terms: list of (coef, base, npow) -> value of sum coef * n^npow * base^n (exact)."""
    return sum(F(c) * (F(n) ** k) * (F(b) ** n) for c, b, k in terms)

def verify(p, q, g, a0, a1, terms, N=25):
    a = iterate(p, q, g, a0, a1, N)
    for n in range(N + 1):
        assert ev(terms, n) == a[n], (p, q, a0, a1, terms, n, ev(terms, n), a[n])

def zero(n): return 0

def satisfies_rec(seq, p, q, g, start=2, N=15):
    return all(seq(n) == p * seq(n - 1) + q * seq(n - 2) + g(n) for n in range(start, N))

# ---------- formatting ----------
def num(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else r"\frac{%d}{%d}" % (x.numerator, x.denominator)

def base_tex(b):
    return str(b) if b >= 0 else "(%d)" % b

def term_tex(c, b, k):
    c = F(c)
    body = []
    if k == 1: body.append("n")
    elif k > 1: body.append("n^%d" % k)
    if b != 1: body.append("%s^n" % base_tex(b))
    mag = abs(c)
    parts = []
    if mag != 1 or not body: parts.append(num(mag))
    parts += body
    return ("-" if c < 0 else "") + r"\cdot ".join(parts)

def terms_tex(terms):
    out = ""
    for i, (c, b, k) in enumerate(terms):
        t = term_tex(c, b, k)
        if i == 0: out += t
        else: out += t if t.startswith("-") else "+" + t
    return out

def tex(s): return "$" + s + "$"

# ---------- question builders ----------
LETTERS = "abcdefgh"

def mc(qid, question, correct, wrongs, explanation, recap, pos=0):
    opts = list(wrongs)
    pos = pos % (len(opts) + 1)
    opts.insert(pos, correct)
    assert len(set(opts)) == len(opts), (qid, opts)
    return {"id": qid, "question": question,
            "options": [{"id": LETTERS[i], "value": v} for i, v in enumerate(opts)],
            "correctId": LETTERS[pos], "explanation": explanation, "recap": recap}

def numq(qid, prompt, answer, explain, recap):
    a = F(answer)
    assert a.denominator == 1
    return {"id": qid, "step": {"type": "numeric", "prompt": prompt, "answer": int(a), "tol": 0, "explain": explain}, "recap": recap}

def orderq(qid, prompt, lines, explain, recap):
    return {"id": qid, "step": {"type": "order", "prompt": prompt, "lines": lines, "explain": explain}, "recap": recap}

def bugq(qid, prompt, lines, bug, explain, recap):
    return {"id": qid, "step": {"type": "findbug", "prompt": prompt, "lines": lines, "bugIndex": bug, "explain": explain}, "recap": recap}

def bank(bid, recap): return {"bankId": bid, "recap": recap}

def rec_tex(p, q, c=None, s=None, cc=1):
    """a_n = p a_{n-1} + q a_{n-2} (+ c) (+ cc*s^n) as TeX"""
    def coef(v, sym):
        return ("-" if v < 0 else "+") + ("" if abs(v) == 1 else str(abs(v))) + sym
    t = ""
    if p: t += coef(p, "a_{n-1}")
    if q: t += coef(q, "a_{n-2}")
    if c is not None: t += ("+" if c > 0 else "-") + str(abs(c))
    if s is not None: t += ("+" if cc > 0 else "-") + ("" if abs(cc) == 1 else str(abs(cc)) + r"\cdot ") + "%d^n" % s
    if t.startswith("+"): t = t[1:]
    return "a_n=" + t

def charroots(p, q):
    d = p * p + 4 * q
    assert d >= 0
    r = int(round(d ** 0.5)); assert r * r == d
    return sorted([F(p - r, 2), F(p + r, 2)])

def partA(p, q, s, c):
    """coefficient A of the particular solution A s^n (s not a char root), computed from the recurrence"""
    den = s * s - p * s - q
    assert den != 0
    return F(c * s * s, den)

def check_partA(p, q, s, c, A):
    seq = lambda n: A * F(s) ** n
    assert satisfies_rec(seq, p, q, lambda n: c * F(s) ** n)


