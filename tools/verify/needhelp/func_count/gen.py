def clean(x):
    # raw strings keep the backslash of \" -- drop it
    if isinstance(x, str):
        import re
        return re.sub(r'<b>(.*?)</b>', lambda m: '**' + m.group(1) + '**', x.replace('\\"', '"'))
    if isinstance(x, list):
        return [clean(i) for i in x]
    if isinstance(x, dict):
        return {k: clean(v) for k, v in x.items()}
    return x

def mcq(qid, question, opts, ci, target, explanation, recap):
    vals = [v for _, v in opts]
    assert vals[ci] == target, (qid, vals, target)
    assert vals.count(target) == 1, (qid, "duplicate value", vals)
    return clean({"id": qid, "question": question,
            "options": [{"id": "abcd"[i], "value": t} for i, (t, _) in enumerate(opts)],
            "correctId": "abcd"[ci], "explanation": explanation, "recap": recap})

def num(qid, prompt, target, formula, explain, recap):
    assert target == formula, (qid, target, formula)
    return clean({"id": qid, "step": {"type": "numeric", "prompt": prompt, "answer": target, "tol": 0, "explain": explain},
            "recap": recap})

def bank(i, recap):
    return clean({"bankId": i, "recap": recap})

